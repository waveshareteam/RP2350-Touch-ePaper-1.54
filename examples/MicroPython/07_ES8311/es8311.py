class ES8311:
    def __init__(self, i2c, addr=ES8311_I2C_ADDR):
        self.i2c = i2c
        self.addr = addr

    def write_reg(self, reg_addr, data):
        self.i2c.writeto(self.addr, bytes([reg_addr, data]))

    def read_reg(self, reg_addr):
        self.i2c.writeto(self.addr, bytes([reg_addr]))
        result = bytearray(1)
        self.i2c.readfrom_into(self.addr, result)
        return result[0]

    def get_coeff(self, mclk, rate):
        for i, coeff in enumerate(COEFF_DIV):
            if coeff[1] == rate and coeff[0] == mclk:
                return i
        return -1

    def sample_frequency_config(self, mclk_frequency, sample_frequency):
        coeff_idx = self.get_coeff(mclk_frequency, sample_frequency)
        if coeff_idx < 0:
            print(f"Unable to configure sample rate {sample_frequency}Hz with {mclk_frequency}Hz MCLK")
            return -1

        coeff = COEFF_DIV[coeff_idx]
        pre_div = coeff[2]
        pre_multi = coeff[3]
        adc_div = coeff[4]
        dac_div = coeff[5]
        fs_mode = coeff[6]
        adc_osr = coeff[10]
        dac_osr = coeff[11]
        lrck_h = coeff[7]
        lrck_l = coeff[8]
        bclk_div = coeff[9]

        regv = self.read_reg(ES8311_CLK_MANAGER_REG02)
        regv &= 0x07
        regv |= (pre_div - 1) << 5
        regv |= pre_multi << 3
        self.write_reg(ES8311_CLK_MANAGER_REG02, regv)

        reg03 = (fs_mode << 6) | adc_osr
        self.write_reg(ES8311_CLK_MANAGER_REG03, reg03)

        self.write_reg(ES8311_CLK_MANAGER_REG04, dac_osr)

        reg05 = ((adc_div - 1) << 4) | (dac_div - 1)
        self.write_reg(ES8311_CLK_MANAGER_REG05, reg05)

        regv = self.read_reg(ES8311_CLK_MANAGER_REG06)
        regv &= 0xE0
        if bclk_div < 19:
            regv |= (bclk_div - 1) << 0
        else:
            regv |= bclk_div << 0
        self.write_reg(ES8311_CLK_MANAGER_REG06, regv)

        self.write_reg(ES8311_CLK_MANAGER_REG07, lrck_h & 0x3F)

        self.write_reg(ES8311_CLK_MANAGER_REG08, lrck_l)

        return 0

    def clock_config(self, mclk_freq, sample_freq, res_out):
        reg01 = 0x3F
        mclk_hz = mclk_freq

        self.write_reg(ES8311_CLK_MANAGER_REG01, reg01)

        reg06 = self.read_reg(ES8311_CLK_MANAGER_REG06)
        reg06 |= 0x03
        self.write_reg(ES8311_CLK_MANAGER_REG06, reg06)

        self.sample_frequency_config(mclk_hz, sample_freq)

    def resolution_config(self, res):
        if res == 16:
            return 3 << 2
        elif res == 18:
            return 2 << 2
        elif res == 20:
            return 1 << 2
        elif res == 24:
            return 0 << 2
        elif res == 32:
            return 4 << 2
        return 0

    def fmt_config(self, res_in, res_out):
        reg09 = 0
        reg0a = 0

        print("ES8311 in Master mode and I2S format")
        reg00 = self.read_reg(ES8311_RESET_REG00)
        reg00 |= 0x40
        self.write_reg(ES8311_RESET_REG00, reg00)

        reg09 |= self.resolution_config(res_out)
        reg0a |= self.resolution_config(res_in)

        self.write_reg(ES8311_SDPIN_REG09, reg09)
        self.write_reg(ES8311_SDPOUT_REG0A, reg0a)

        return 0

    def microphone_config(self):
        reg14 = 0x1A
        self.write_reg(ES8311_ADC_REG17, 0xFF)
        self.write_reg(ES8311_SYSTEM_REG14, reg14)

    def init(self, mclk_freq, sample_freq, res_in=16, res_out=16, volume=60, mic_gain=3):
        self.write_reg(ES8311_RESET_REG00, 0x1F)
        time.sleep_ms(20)
        self.write_reg(ES8311_RESET_REG00, 0x00)
        self.write_reg(ES8311_RESET_REG00, 0x80)

        self.clock_config(mclk_freq, sample_freq, res_out)
        self.fmt_config(res_in, res_out)

        self.write_reg(ES8311_SYSTEM_REG0D, 0x01)
        self.write_reg(ES8311_SYSTEM_REG0E, 0x02)
        self.write_reg(ES8311_SYSTEM_REG12, 0x00)
        self.write_reg(ES8311_SYSTEM_REG13, 0x10)
        self.write_reg(ES8311_ADC_REG1C, 0x6A)
        self.write_reg(ES8311_DAC_REG37, 0x08)

        self.volume_set(volume)
        self.microphone_gain_set(mic_gain)
        self.microphone_config()

    def volume_set(self, volume):
        if volume < 0:
            volume = 0
        elif volume > 100:
            volume = 100

        if volume == 0:
            reg32 = 0
        else:
            reg32 = (volume * 256 // 100) - 1

        self.write_reg(ES8311_DAC_REG32, reg32)
        return volume

    def volume_get(self):
        reg32 = self.read_reg(ES8311_DAC_REG32)
        if reg32 == 0:
            volume = 0
        else:
            volume = (reg32 * 100) // 256 + 1
        return volume

    def mute(self, mute):
        reg31 = self.read_reg(ES8311_DAC_REG31)
        if mute:
            reg31 |= (1 << 6) | (1 << 5)
        else:
            reg31 &= ~((1 << 6) | (1 << 5))
        self.write_reg(ES8311_DAC_REG31, reg31)

    def microphone_gain_set(self, gain_db):
        self.write_reg(ES8311_ADC_REG16, gain_db)

    def read_id(self):
        chip_id_LSB = self.read_reg(ES8311_CHD1_REGFD)
        chip_id_MSB = self.read_reg(ES8311_CHD2_REGFE)
        chip_id = (chip_id_MSB << 8) + chip_id_LSB
        return chip_id

    def register_dump(self):
        for reg in range(0x4A):
            value = self.read_reg(reg)
            print(f"REG:{reg:02x}: {value:02x}")
